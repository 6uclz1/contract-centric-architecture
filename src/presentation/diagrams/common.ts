export const nodeId = (kind: string, ...parts: string[]) =>
  "n_" +
  [kind, ...parts].map((s) => Buffer.from(s, "utf8").toString("hex")).join("_");
// Mermaid's quoted label entities use decimal #...; syntax. Encode syntax punctuation,
// HTML and literal entity introducers before Mermaid's renderer sees them.
const encoded = (s: string) =>
  Array.from(s.replace(/\r\n?|\n/g, " "))
    .map((c) => (/[\p{L}\p{N} _.,:-]/u.test(c) ? c : `#${c.codePointAt(0)};`))
    .join("");
export const erLabel = (s: string) => encoded(s);
// The ER lexer reserves PK/FK/UK case-insensitively, including before a hyphen.
// It has no quoted attribute identifiers. Reserve our alias prefix as well so
// a real field named cca_field_504b cannot collide with the alias for PK.
export const erAttributeName = (id: string) =>
  /^(?:PK|FK|UK)\b/i.test(id) || id.startsWith("cca_field_")
    ? `cca_field_${Buffer.from(id, "utf8").toString("hex")}`
    : id;
export const classLabel = (s: string) => encoded(s).replace(/:/g, "#58;");
export const stateLabel = (s: string) => encoded(s).replace(/:/g, "#58;");
export const header = (kind: string) => [
  `%% Generated by cca v0.1; catalog: ./catalog.md`,
  kind,
];
